function AoDJPProbe_prepareKnownFonts() {
   AoDJPProbe_applyKnownProfiles();
   if (isFunction("populateFontCacheString")) {
      %sample = "日本語　ひらがな　カタカナ　漢字　、。「」";
      %sizes = "15 16 17 20 22 24 32";
      for (%i = 0; %i < getWordCount(%sizes); %i++) populateFontCacheString("BIZ UDPMincho Medium", getWord(%sizes, %i), %sample);
   }
   echo("AoDJPProbe: known profile definitions applied (v5).");
}
